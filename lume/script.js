let currentLanguage = "it";
let activeCategory = "antipasti";

function renderMenu(category) {
  activeCategory = category;
  const list = document.getElementById("menuList");
  list.replaceChildren();
  const items = dishes[category] || [];
  if (!items.length) {
    list.textContent = translations[currentLanguage].menuEmpty;
    return;
  }
  items.forEach(function(item) {
    const article = document.createElement("article");
    article.className = "menu-item";
    const head = document.createElement("div");
    head.className = "menu-item-head";
    const title = document.createElement("h3");
    title.textContent = currentLanguage === "it" ? item.name : item.en;
    const price = document.createElement("span");
    price.className = "menu-item-price";
    price.textContent = "€ " + item.price;
    const description = document.createElement("p");
    description.textContent = currentLanguage === "it" ? item.desc : item.enDesc;
    head.append(title, price);
    article.append(head, description);
    list.append(article);
  });
  document.querySelectorAll(".menu-tab").forEach(function(button) {
    const selected = button.dataset.category === category;
    button.classList.toggle("active", selected);
    button.setAttribute("aria-selected", String(selected));
  });
}

function setLanguage(language) {
  currentLanguage = language;
  document.documentElement.lang = language;
  document.querySelectorAll("[data-i18n]").forEach(function(element) {
    const key = element.dataset.i18n;
    if (translations[language][key]) element.innerHTML = translations[language][key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function(element) {
    const key = element.dataset.i18nPlaceholder;
    if (translations[language][key]) element.placeholder = translations[language][key];
  });
  document.querySelectorAll("[data-lang]").forEach(function(button) {
    const selected = button.dataset.lang === language;
    button.classList.toggle("active", selected);
    button.setAttribute("aria-pressed", String(selected));
  });
  const message = document.getElementById("formMessage");
  message.textContent = "";
  renderMenu(activeCategory);
}

document.querySelectorAll("[data-lang]").forEach(function(button) {
  button.addEventListener("click", function() {
    setLanguage(button.dataset.lang);
  });
});
document.querySelectorAll(".menu-tab").forEach(function(button) {
  button.addEventListener("click", function() {
    renderMenu(button.dataset.category);
  });
});

const navToggle = document.querySelector(".nav-toggle");
const navLinks = document.querySelector(".nav-links");
navToggle.addEventListener("click", function() {
  const isOpen = navToggle.getAttribute("aria-expanded") === "true";
  navToggle.setAttribute("aria-expanded", String(!isOpen));
  navLinks.classList.toggle("open", !isOpen);
});
navLinks.querySelectorAll("a").forEach(function(link) {
  link.addEventListener("click", function() {
    navLinks.classList.remove("open");
    navToggle.setAttribute("aria-expanded", "false");
  });
});

